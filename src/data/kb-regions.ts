export function normalizeKbCountry(value: unknown): KbCountry {
  return typeof value === "string" && (KB_COUNTRIES as readonly string[]).includes(value)
    ? (value as KbCountry)
    : "RU";
}

export function kbRegionsFor(country: KbCountry): readonly string[] {
  return REGIONS[country];
}

/** The region after the person picks a country: kept for the same country, cleared for another. */
export function kbRegionAfterCountryChange(
  previous: KbCountry,
  next: KbCountry,
  region: string | null,
): string | null {
  return previous === next ? region : null;
}

/** A region kept only when it belongs to the country; anything else is «not selected». */
export function normalizeKbRegion(country: KbCountry, value: unknown): string | null {
  return typeof value === "string" && REGIONS[country].includes(value) ? value : null;
}
